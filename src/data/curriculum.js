export const courseById = Object.fromEntries(COURSES.map((c) => [c.id, c]));
export const unitById = Object.fromEntries(COURSES.flatMap((c) => c.units.map((u) => [u.id, { ...u, course: c }])));
export const sectionById = Object.fromEntries(
  COURSES.flatMap((c) => c.units.flatMap((u) => u.sections.map((s) => [s.id, { ...s, unit: u, course: c }])))
);
export const standardByCode = Object.fromEntries(STANDARDS.map((s) => [s.code, s]));

// 단원 위치 문자열. 예: "화학 Ⅲ. 화학 평형 › 2. 화학 평형의 이동"
export function placeLabel(id) {
  const s = sectionById[id];
  if (s) return `${s.course.name} ${s.unit.no}. ${s.unit.title} › ${s.no}. ${s.title}`;
  const u = unitById[id];
  return u ? `${u.course.name} ${u.no}. ${u.title}` : id;
}
